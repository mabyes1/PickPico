      "Let the host client exchange and securely store tokens, refresh and rotate them automatically, then retry the original MCP operation. Never ask the user to paste tokens or secrets into chat.",
      "If a saved access token expires, first use the saved refresh token. Reconnect only when refresh is unavailable, expired, or revoked; do not initiate repeated phone prompts.",
      "If the host application does not support MCP OAuth, explain that it needs an OAuth-capable client. Do not select no authentication, bypass authorization, reinstall the APK, or reset pairing to fix this.",
