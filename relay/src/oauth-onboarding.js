export function oauthOnboardingResponse(request, response, guide) {
  const headers = new Headers(response.headers);
  headers.delete("Content-Length");
  headers.set("Cache-Control", "no-store");
  headers.set("Link", `<${guide.documentation_url}>; rel="help"`);
  headers.set("Vary", headers.has("Vary") ? `${headers.get("Vary")}, Accept` : "Accept");
  // Preserve the provider's challenge, especially invalid_token and scopes.
  if (!headers.has("WWW-Authenticate")) headers.set("WWW-Authenticate",
    `Bearer resource_metadata="${guide.resource_metadata}", scope="phone"`);
  if ((request.headers.get("Accept") || "").includes("text/html")) {
    const html = connectionGuidePage(guide, headers);
    return new Response(html.body, { status: 401, headers: html.headers });
  }
  headers.set("Content-Type", "application/json; charset=utf-8");
  headers.delete("Content-Length");
  return new Response(JSON.stringify({
    error: request.headers.has("Authorization") ? "invalid_token" : "authorization_required",
    next_action: request.headers.has("Authorization") ? "refresh_or_reauthorize" : "connect_with_oauth",
    error_description: request.headers.has("Authorization")
      ? "The access token was rejected. Let the host client first refresh its saved credentials. Start OAuth linking only if refresh fails or is unavailable; do not repeatedly prompt the phone holder. No APK reinstall is needed."
      : "PickPico requires MCP OAuth. Start the host client's OAuth connection flow; the Relay will request the phone holder's approval through existing human_help. No APK reinstall is needed.",
    ...!request.headers.has("Authorization") ? { commandDispatched: false } : {}, onboarding: guide,
  }), { status: 401, headers });
}
